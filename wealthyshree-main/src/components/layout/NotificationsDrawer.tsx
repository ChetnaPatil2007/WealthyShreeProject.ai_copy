import { useState } from "react"
import type { NotificationItem } from "../../types/layout"
import { Icon } from "../ui/Icon"

export interface NotificationsDrawerProps {
  notifications: NotificationItem[]
  isOpen: boolean
  onClose: () => void
  onActionClick?: (item: NotificationItem) => void
}

export function NotificationsDrawer({
  notifications: initialNotifications,
  isOpen,
  onClose,
  onActionClick,
}: NotificationsDrawerProps) {
  const [items, setItems] = useState<NotificationItem[]>(initialNotifications)
  const [filter, setFilter] = useState<"all" | "unread">("all")

  if (!isOpen) return null

  const unreadCount = items.filter((n) => !n.read).length

  const handleMarkAllRead = () => {
    setItems((prev) => prev.map((n) => ({ ...n, read: true })))
  }

  const handleItemClick = (item: NotificationItem) => {
    setItems((prev) =>
      prev.map((n) => (n.id === item.id ? { ...n, read: true } : n)),
    )
    if (onActionClick) {
      onActionClick(item)
    }
  }

  const filteredItems = items.filter((item) =>
    filter === "unread" ? !item.read : true,
  )

  return (
    <>
      <div
        className="notifications-backdrop"
        onClick={onClose}
        aria-hidden="true"
      />
      <div
        className="notifications-popover"
        role="dialog"
        aria-label="Notifications"
      >
        <div className="notifications-header">
          <div className="notif-title-group">
            <span className="notif-title">Notifications</span>
            {unreadCount > 0 && (
              <span className="badge badge--warning">{unreadCount} new</span>
            )}
          </div>
          <div className="notif-actions-header">
            {unreadCount > 0 && (
              <button
                type="button"
                className="mark-all-read-btn"
                onClick={handleMarkAllRead}
              >
                Mark all read
              </button>
            )}
            <button
              type="button"
              className="notif-close-btn"
              onClick={onClose}
              aria-label="Close notifications"
            >
              ×
            </button>
          </div>
        </div>

        <div className="notif-filter-tabs">
          <button
            type="button"
            className={filter === "all" ? "active" : ""}
            onClick={() => setFilter("all")}
          >
            All ({items.length})
          </button>
          <button
            type="button"
            className={filter === "unread" ? "active" : ""}
            onClick={() => setFilter("unread")}
          >
            Unread ({unreadCount})
          </button>
        </div>

        <div className="notifications-list">
          {filteredItems.length > 0 ? (
            filteredItems.map((item) => (
              <div
                key={item.id}
                className={`notif-card priority-${item.priority} ${
                  item.read ? "read" : "unread"
                }`}
                onClick={() => handleItemClick(item)}
              >
                <div className="notif-top-row">
                  <span className={`notif-badge tone-${item.priority}`}>
                    {item.priority.toUpperCase()}
                  </span>
                  <span className="notif-timestamp">{item.timestamp}</span>
                </div>

                <strong className="notif-card-title">{item.title}</strong>
                <p className="notif-message">{item.message}</p>

                {item.actionLabel && (
                  <button
                    type="button"
                    className="notif-action-link"
                    onClick={(e) => {
                      e.stopPropagation()
                      handleItemClick(item)
                    }}
                  >
                    <span>{item.actionLabel}</span>
                    <Icon name="arrow" size={12} />
                  </button>
                )}
              </div>
            ))
          ) : (
            <div className="notifications-empty">
              <Icon name="shield" size={24} />
              <span>
                No {filter === "unread" ? "unread" : ""} alerts right now.
              </span>
            </div>
          )}
        </div>

        <div className="notifications-footer">
          <Icon name="shield" size={12} />
          <span>Real-time intelligence generated by Sphere AI Engine</span>
        </div>
      </div>
    </>
  )
}

export default NotificationsDrawer
